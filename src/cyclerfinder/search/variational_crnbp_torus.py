def correct_crnbp_torus_pseudospectral(
    system: crnbp.CRNBPSystem,
    coeffs0: NDArray[np.float64],
    omega2_0: float,
    *,
    n1: int,
    n2: int,
    amplitude_anchor: float,
    period_multiple: int = 1,
    rho_target: float | None = None,
    rho_weight: float = 1.0,
    m1: int | None = None,
    m2: int | None = None,
    tol: float = 1e-6,
    closure_tol: float = 1e-4,
    max_nfev: int = 200,
    gauge_weight: float = 1.0,
    tr_solver: Literal["exact", "lsmr"] = "exact",
    closure_dt_frac: float = 0.02,
    n_closure_samples: int = 12,
    notes: str = "",
) -> CRNBPTorusVariationalResult:
    """Refine a 2D-Fourier planar CRNBP torus guess to zero invariance residual.

    ``system.perturbers`` MUST be ``(io, ganymede)`` in that order (the exact
    convention :func:`cyclerfinder.core.crnbp.jupiter_europa_io_ganymede_default`
    constructs) -- the LAST perturber is the forcing clock (``omega1 =
    period_multiple * |perturbers[-1].omega|``), matching `#690`'s Ganymede
    clock exactly; any earlier perturbers (here, Io) have their phase slaved to
    that same absolute time via their own ``omega``/``theta0``. Everything
    else mirrors
    :func:`cyclerfinder.search.variational_ccr4bp_torus.correct_ccr4bp_torus_pseudospectral`.
    """
    if coeffs0.shape != (_N_STATE, 2 * n1 + 1, 2 * n2 + 1):
        raise ValueError(
            f"coeffs0 shape {coeffs0.shape} != expected {(_N_STATE, 2 * n1 + 1, 2 * n2 + 1)}"
        )
    if period_multiple < 1:
        raise ValueError(f"period_multiple must be >= 1, got {period_multiple}")
    if not system.perturbers:
        raise ValueError("correct_crnbp_torus_pseudospectral requires >= 1 perturber (clock)")
    mu = system.mu
    clock = system.perturbers[-1]
    omega1 = period_multiple * abs(clock.omega)
    period = 2.0 * np.pi / omega1
    if rho_target is None:
        rho_target = omega2_0 / omega1
    m1 = m1 if m1 is not None else 2 * n1 + 3
    m2 = m2 if m2 is not None else 2 * n2 + 3
    t1 = 2 * np.pi * np.arange(m1) / m1
    t2 = 2 * np.pi * np.arange(m2) / m2
    p1, p1d = _basis_matrices(n1, t1)
    p2, p2d = _basis_matrices(n2, t2)
    perturbers_grid = _perturber_grids(system, t1, omega1)

    cos1, sin1 = _k2_first_harmonic_cols(n2)
    trans_by_coord = np.sqrt(np.sum(coeffs0[:, :, cos1] ** 2 + coeffs0[:, :, sin1] ** 2, axis=1))
    phase2_coord = int(np.argmax(trans_by_coord))

    z0 = _pack(coeffs0, omega2_0)
    solver_args = (
        omega1,
        mu,
        perturbers_grid,
        n1,
        n2,
        p1,
        p1d,
        p2,
        p2d,
        phase2_coord,
        amplitude_anchor,
        gauge_weight,
        rho_target,
        rho_weight,
    )
    sol = least_squares(
        _residual,
        z0,
        jac=_jacobian,
        args=solver_args,
        method="trf",
        tr_solver=tr_solver,
        x_scale="jac",
        xtol=1e-14,
        ftol=1e-14,
        gtol=1e-14,
        max_nfev=max_nfev,
    )
    coeffs, omega2 = _unpack(sol.x, n1, n2)
    n_res = m1 * m2 * _N_STATE
    residual_rms = float(np.sqrt(np.sum(sol.fun[:n_res] ** 2) / n_res))
    amp = _transverse_amplitude(coeffs, n2)
    rot = omega2 / omega1

    result = CRNBPTorusVariationalResult(
        system=system,
        coeffs=coeffs,
        omega1=omega1,
        omega2=omega2,
        rotation_number=rot,
        rho_strob=omega2 * period,
        period=period,
        n1=n1,
        n2=n2,
        m1=m1,
        m2=m2,
        period_multiple=period_multiple,
        transverse_amplitude=amp,
        residual_rms=residual_rms,
        closure_residual=float("nan"),
        converged=False,
        n_iter=int(sol.nfev),
        notes=notes,
    )
    closure = _independent_closure(result, closure_dt_frac, n_closure_samples)
    converged = (residual_rms < tol) and (closure < closure_tol)
    result = replace(result, closure_residual=closure, converged=converged)
    io_mu = system.perturbers[0].mu if len(system.perturbers) >= 1 else 0.0
    gan_mu = system.perturbers[-1].mu
    log_outcome(
        solver="variational_crnbp_torus.correct_crnbp_torus_pseudospectral",
        inputs={
            "mu": float(mu),
            "mu_io": float(io_mu),
            "mu_gan": float(gan_mu),
            "n1": int(n1),
            "n2": int(n2),
            "period_multiple": int(period_multiple),
            "amplitude_anchor": float(amplitude_anchor),
        },
        outcome={
            "converged": bool(converged),
            "residual_rms": residual_rms,
            "closure_residual": closure,
            "omega2": float(omega2),
            "rotation_number": float(rot),
            "rho_strob": float(omega2 * period),
            "transverse_amplitude": float(amp),
        },
        meta={"model": "crnbp"},
    )
    return result


def _independent_closure(
    result: CRNBPTorusVariationalResult, dt_frac: float, n_samples: int
) -> float:
    """Short-time flow-consistency check (independent of the algebraic residual).

    Propagates through the FULL, coupling-term-included
    :func:`cyclerfinder.core.crnbp.crnbp_eom` -- NOT the simplified
    coupling-omitted grid RHS the corrector's residual uses -- so this is also
    the sharpest available runtime confirmation that omitting the coupling
    term from the algebraic residual was safe (`#717`'s zero-net-contribution
    proof). Identical structure to `#690`'s ``_independent_closure``.
    """
    dt = dt_frac * result.period
    rng = np.random.default_rng(0xC0FFEE)
    max_err = 0.0
    for _ in range(n_samples):
        th1 = float(rng.uniform(0, 2 * np.pi))
        th2 = float(rng.uniform(0, 2 * np.pi))
        u0 = evaluate_torus_state(result, th1, th2)
        s6 = np.array([u0[0], u0[1], 0.0, u0[2], u0[3], 0.0], dtype=np.float64)
        t0 = th1 / result.omega1
        sol = solve_ivp(
            crnbp.crnbp_eom,
            (t0, t0 + dt),
            s6,
            args=(result.system,),
            method="DOP853",
            rtol=1e-12,
            atol=1e-12,
        )
        if not sol.success:
            return float("inf")
        u_target = evaluate_torus_state(result, th1 + result.omega1 * dt, th2 + result.omega2 * dt)
        end = sol.y[:, -1]
        planar_end = np.array([end[0], end[1], end[3], end[4]], dtype=np.float64)
        max_err = max(max_err, float(np.linalg.norm(planar_end - u_target)))
    return max_err


