def crnbp_system_at_mu_io(
    ccr4bp_mu: float,
    mu_gan: float,
    a_gan: float,
    omega_gan: float,
    *,
    mu_io: float,
    a_io: float,
    omega_io: float,
    theta_io0: float = 0.0,
    theta_gan0: float = 0.0,
) -> crnbp.CRNBPSystem:
    """Build a ``(io, ganymede)``-ordered :class:`crnbp.CRNBPSystem` from a
    CCR4BP system's own ``(mu, mu_gan, a_gan, omega_gan)`` plus an Io
    perturber. ``mu_io = 0.0`` reproduces the CCR4BP system exactly (`#717`
    Gate 1)."""
    io = crnbp.CRNBPPerturber(mu=mu_io, a=a_io, omega=omega_io, theta0=theta_io0)
    gan = crnbp.CRNBPPerturber(mu=mu_gan, a=a_gan, omega=omega_gan, theta0=theta_gan0)
    return crnbp.CRNBPSystem(mu=ccr4bp_mu, perturbers=(io, gan))


def discover_crnbp_torus_from_ccr4bp_seed(
    ccr4bp_result: CCR4BPTorusVariationalResult,
    *,
    mu_io: float,
    a_io: float,
    omega_io: float,
    theta_io0: float = 0.0,
    rho_weight: float = 100.0,
    gauge_weight: float = 30.0,
    tr_solver: Literal["exact", "lsmr"] = "exact",
    tol: float = 1e-6,
    closure_tol: float = 1e-4,
    max_nfev: int = 600,
    closure_dt_frac: float = 0.02,
    notes: str = "",
) -> CRNBPTorusVariationalResult:
    """Seed an N=5 CRNBP torus corrector from `#690`'s own converged
    ``CCR4BPTorusVariationalResult`` (``ccr4bp_result``).

    At ``mu_io = 0.0`` this reproduces the CCR4BP torus exactly (Tier-0 gate);
    at ``mu_io > 0`` it is the FIRST corrector solve of the N=5 continuation
    (normally called via :func:`continue_crnbp_torus_mu_io` instead, which
    walks ``mu_io`` up gradually from this ``mu_io=0`` anchor).
    """
    base = ccr4bp_result.system
    system = crnbp_system_at_mu_io(
        base.mu,
        base.mu_gan,
        base.a_gan,
        base.omega_gan,
        mu_io=mu_io,
        a_io=a_io,
        omega_io=omega_io,
        theta_io0=theta_io0,
        theta_gan0=base.theta_gan0,
    )
    return correct_crnbp_torus_pseudospectral(
        system,
        ccr4bp_result.coeffs,
        ccr4bp_result.omega2,
        n1=ccr4bp_result.n1,
        n2=ccr4bp_result.n2,
        m1=ccr4bp_result.m1,
        m2=ccr4bp_result.m2,
        period_multiple=ccr4bp_result.period_multiple,
        amplitude_anchor=ccr4bp_result.transverse_amplitude,
        rho_target=ccr4bp_result.rotation_number,
        rho_weight=rho_weight,
        gauge_weight=gauge_weight,
        tr_solver=tr_solver,
        tol=tol,
        closure_tol=closure_tol,
        max_nfev=max_nfev,
        closure_dt_frac=closure_dt_frac,
        notes=notes or "seeded_from_ccr4bp_mu_io_zero",
    )


def continue_crnbp_torus_mu_io(
    result: CRNBPTorusVariationalResult,
    target_system: crnbp.CRNBPSystem,
    *,
    n_steps: int = 8,
    rho_weight: float = 1.0,
    gauge_weight: float = 1.0,
    tr_solver: Literal["exact", "lsmr"] = "exact",
    tol: float = 1e-6,
    closure_tol: float = 1e-4,
    max_nfev: int = 400,
    closure_dt_frac: float = 0.02,
    divergence_factor: float = 1.0e3,
) -> list[CRNBPTorusVariationalResult]:
    """Homotopy in Io's mass from ``result.system.perturbers[0].mu`` to
    ``target_system.perturbers[0].mu`` (nominally 0 -> the Laplace-projected
    physical value, ~4.7e-5), holding Ganymede's ``(mu, a, omega, theta0)``
    and Io's own ``(a, omega, theta0)`` fixed at the target's.

    Mirrors
    :func:`cyclerfinder.search.variational_ccr4bp_torus.continue_ccr4bp_torus_mass`
    exactly, one level up (Io's mass instead of Ganymede's). Stops early only
    on genuine DIVERGENCE (non-finite residual or one growing past
    ``divergence_factor`` times the seed's), not on the strict ``converged``
    flag -- the honest per-step residual is what should be reported.
    """
    io0 = result.system.perturbers[0]
    gan_t = target_system.perturbers[-1]
    io_t = target_system.perturbers[0]
    steps: list[CRNBPTorusVariationalResult] = []
    current = result
    floor = max(result.residual_rms, 1.0e-6)
    mu_ios = np.linspace(io0.mu, io_t.mu, n_steps + 1)[1:]
    for mi in mu_ios:
        io_step = replace(io_t, mu=float(mi))
        sys_step = crnbp.CRNBPSystem(mu=target_system.mu, perturbers=(io_step, gan_t))
        nxt = correct_crnbp_torus_pseudospectral(
            sys_step,
            current.coeffs,
            current.omega2,
            n1=current.n1,
            n2=current.n2,
            m1=current.m1,
            m2=current.m2,
            period_multiple=current.period_multiple,
            amplitude_anchor=current.transverse_amplitude,
            rho_target=current.rotation_number,
            rho_weight=rho_weight,
            gauge_weight=gauge_weight,
            tr_solver=tr_solver,
            tol=tol,
            closure_tol=closure_tol,
            max_nfev=max_nfev,
            closure_dt_frac=closure_dt_frac,
            notes=f"mu_io_continuation_mu_io={mi:.6e}",
        )
        steps.append(nxt)
        current = nxt
        if not np.isfinite(nxt.residual_rms) or nxt.residual_rms > divergence_factor * floor:
            break
    return steps
