_N_STATE = 4  # planar rotating-frame state: x, y, vx, vy (identical to CCR4BP)

# A "perturber grid" tuple: (mu_j, a_j, gx_j, gy_j) with gx_j/gy_j shape (m1,)
# -- this perturber's synodic-frame position sampled at every theta1 grid
# value, mass folded in for a cheap mu_j == 0 skip.
_PerturberGrid = tuple[float, float, NDArray[np.float64], NDArray[np.float64]]


@dataclass(frozen=True)
class CRNBPTorusVariationalResult:
    """An N=5 CRNBP quasi-periodic 2-torus found by 2D pseudospectral collocation.

    Mirrors :class:`cyclerfinder.search.variational_ccr4bp_torus.CCR4BPTorusVariationalResult`
    field-for-field, with ``system`` typed as :class:`cyclerfinder.core.crnbp.CRNBPSystem`
    (two perturbers -- Io, Ganymede -- instead of one).
    """

    system: crnbp.CRNBPSystem
    coeffs: NDArray[np.float64]
    omega1: float
    omega2: float
    rotation_number: float
    rho_strob: float
    period: float
    n1: int
    n2: int
    m1: int
    m2: int
    period_multiple: int
    transverse_amplitude: float
    residual_rms: float
    closure_residual: float
    converged: bool
    n_iter: int
    notes: str = ""
    extras: dict[str, float] = field(default_factory=dict)


def evaluate_torus_state(
    result: CRNBPTorusVariationalResult,
    theta1: float | NDArray[np.float64],
    theta2: float | NDArray[np.float64],
) -> NDArray[np.float64]:
    """Evaluate the 2D Fourier torus state ``u(theta1, theta2)`` (4-vector).

    Identical algorithm to `#690`'s ``evaluate_torus_state`` (duplicated, not
    imported, only because it is typed against this module's own result
    dataclass).
    """
    t1 = np.atleast_1d(np.asarray(theta1, dtype=np.float64))
    t2 = np.atleast_1d(np.asarray(theta2, dtype=np.float64))
    p1, _ = _basis_matrices(result.n1, t1)
    p2, _ = _basis_matrices(result.n2, t2)
    out = np.empty((t1.size, _N_STATE))
    for c in range(_N_STATE):
        full = p1 @ result.coeffs[c] @ p2.T
        out[:, c] = np.diagonal(full) if t1.size == t2.size else full[:, 0]
    if np.isscalar(theta1) and np.isscalar(theta2):
        return np.asarray(out[0], dtype=np.float64)
    return out


# ---------------------------------------------------------------------------
# Pack / unpack (identical to the CCR4BP corrector).
# ---------------------------------------------------------------------------


def _pack(coeffs: NDArray[np.float64], omega2: float) -> NDArray[np.float64]:
    return np.concatenate([coeffs.reshape(-1), [omega2]])


def _unpack(z: NDArray[np.float64], n1: int, n2: int) -> tuple[NDArray[np.float64], float]:
    n_coef = _N_STATE * (2 * n1 + 1) * (2 * n2 + 1)
    coeffs = z[:n_coef].reshape(_N_STATE, 2 * n1 + 1, 2 * n2 + 1)
    return coeffs, float(z[-1])


# ---------------------------------------------------------------------------
# Perturber phase sampling, vectorized CRNBP RHS, and its state-Jacobian.
# ---------------------------------------------------------------------------


def _perturber_on_theta1(
    perturber: crnbp.CRNBPPerturber, theta1: NDArray[np.float64], omega1: float
) -> tuple[NDArray[np.float64], NDArray[np.float64]]:
    """This perturber's synodic-frame ``(gx, gy)`` position at each ``theta1``.

    ``theta1`` locks to the (Ganymede) clock via ``t = theta1 / omega1``
    (same convention as `#690`'s ``_ganymede_on_theta1``); each perturber's
    OWN phase then advances at its own rate from that shared absolute time,
    ``theta_j(t) = theta0_j + omega_j * t`` -- exactly
    :meth:`cyclerfinder.core.crnbp.CRNBPPerturber.position`, vectorized. For
    Io this automatically reproduces the exact Laplace-lock slaving
    (``omega_io = -2 * omega_gan``) baked into the perturber's own ``omega``
    field -- no separate slaving formula needed here.
    """
    t = theta1 / omega1
    theta = perturber.theta0 + perturber.omega * t
    return perturber.a * np.cos(theta), perturber.a * np.sin(theta)


def _perturber_grids(
    system: crnbp.CRNBPSystem, theta1: NDArray[np.float64], omega1: float
) -> tuple[_PerturberGrid, ...]:
    return tuple((p.mu, p.a, *_perturber_on_theta1(p, theta1, omega1)) for p in system.perturbers)


def _crnbp_rhs_grid(
    u: NDArray[np.float64],
    mu: float,
    perturbers: tuple[_PerturberGrid, ...],
) -> NDArray[np.float64]:
    """Vectorized planar CRNBP RHS on the grid: ``u`` shape ``(4, m1, m2)`` ->
    ``(4, m1, m2)``.

    Base CR3BP pseudo-potential gradient + Coriolis, PLUS each perturber's own
    direct + indirect term (`#690`'s single-perturber formula, summed over
    ``perturbers``). The mutual Io-Ganymede COUPLING term (`#717`'s Eq. 11
    inner sum) is deliberately OMITTED here: `#717` proved algebraically,
    numerically, and by an independent re-derivation that it contributes
    EXACTLY ZERO to the total spacecraft acceleration for any N (an exact
    antisymmetric pairwise cancellation, not an approximation) -- see
    ``core.crnbp``'s module docstring and
    ``tests/core/test_crnbp.py::test_coupling_term_net_contribution_is_exactly_zero``.
    So this vectorized RHS reduces to :func:`cyclerfinder.core.crnbp.crnbp_eom`
    EXACTLY (not approximately) at every grid point -- checked pointwise in
    ``tests/search/test_variational_crnbp_torus.py`` against the FULL
    coupling-included ``crnbp_eom``, which is the sharpest possible structural
    confirmation that the omission is safe.
    """
    x, y, vx, vy = u[0], u[1], u[2], u[3]
    r1c = ((x + mu) ** 2 + y * y) ** 1.5
    r2c = ((x - 1.0 + mu) ** 2 + y * y) ** 1.5
    om1 = 1.0 - mu
    ax = x + 2.0 * vy - om1 * (x + mu) / r1c - mu * (x - 1.0 + mu) / r2c
    ay = y - 2.0 * vx - om1 * y / r1c - mu * y / r2c
    for mu_j, a_j, gxj, gyj in perturbers:
        if mu_j == 0.0:
            continue
        gxb, gyb = gxj[:, None], gyj[:, None]
        dxg = x - gxb
        dyg = y - gyb
        dg3 = (dxg * dxg + dyg * dyg) ** 1.5
        a_j3 = a_j**3
        ax = ax - mu_j * dxg / dg3 - mu_j * gxb / a_j3
        ay = ay - mu_j * dyg / dg3 - mu_j * gyb / a_j3
    return np.stack([vx, vy, ax, ay], axis=0)


def _crnbp_jacobian_grid(
    u: NDArray[np.float64],
    mu: float,
    perturbers: tuple[_PerturberGrid, ...],
) -> NDArray[np.float64]:
    """Vectorized 4x4 state-Jacobian ``dF/du`` at every grid point.

    Base CR3BP Hessian + Coriolis + each perturber's own direct-term Hessian
    block, summed. The coupling term contributes nothing here on TWO
    independent grounds (either alone sufficient): it is spacecraft-state-
    independent (zero derivative, `#717`'s own finding, true term-by-term, not
    just in aggregate), and its total contribution is exactly zero regardless.
    """
    x, y = u[0], u[1]
    r1c = ((x + mu) ** 2 + y * y) ** 1.5
    r2c = ((x - 1.0 + mu) ** 2 + y * y) ** 1.5
    r1f = ((x + mu) ** 2 + y * y) ** 2.5
    r2f = ((x - 1.0 + mu) ** 2 + y * y) ** 2.5
    om1 = 1.0 - mu
    uxx = (
        1.0
        - om1 / r1c
        - mu / r2c
        + 3.0 * om1 * (x + mu) ** 2 / r1f
        + 3.0 * mu * (x - 1.0 + mu) ** 2 / r2f
    )
    uyy = 1.0 - om1 / r1c - mu / r2c + 3.0 * om1 * y * y / r1f + 3.0 * mu * y * y / r2f
    uxy = 3.0 * om1 * (x + mu) * y / r1f + 3.0 * mu * (x - 1.0 + mu) * y / r2f

    for mu_j, _a_j, gxj, gyj in perturbers:
        if mu_j == 0.0:
            continue
        gxb, gyb = gxj[:, None], gyj[:, None]
        dxg = x - gxb
        dyg = y - gyb
        dg2 = dxg * dxg + dyg * dyg
        dg3 = dg2**1.5
        dg5 = dg2**2.5
        uxx = uxx - mu_j * (1.0 / dg3 - 3.0 * dxg * dxg / dg5)
        uyy = uyy - mu_j * (1.0 / dg3 - 3.0 * dyg * dyg / dg5)
        uxy = uxy + 3.0 * mu_j * dxg * dyg / dg5

    m1, m2 = x.shape
    jf = np.zeros((_N_STATE, _N_STATE, m1, m2))
    ones = np.ones((m1, m2))
    jf[0, 2] = ones
    jf[1, 3] = ones
    jf[2, 0], jf[2, 1], jf[2, 3] = uxx, uxy, 2.0 * ones
    jf[3, 0], jf[3, 1], jf[3, 2] = uxy, uyy, -2.0 * ones
    return jf


# ---------------------------------------------------------------------------
# Invariance-PDE residual and its analytic Jacobian (no integration).
# ---------------------------------------------------------------------------


def _residual(
    z: NDArray[np.float64],
    omega1: float,
    mu: float,
    perturbers: tuple[_PerturberGrid, ...],
    n1: int,
    n2: int,
    p1: NDArray[np.float64],
    p1d: NDArray[np.float64],
    p2: NDArray[np.float64],
    p2d: NDArray[np.float64],
    phase2_coord: int,
    amplitude_anchor: float,
    gauge_weight: float,
    rho_target: float,
    rho_weight: float,
) -> NDArray[np.float64]:
    """Real residual: CRNBP quasi-periodic invariance PDE on the 2D grid + 3 gauges.

    Structurally identical to `#690`'s ``_residual``, with ``(mu_gan, a_gan,
    gx, gy)`` generalized to the ``perturbers`` tuple.
    """
    coeffs, omega2 = _unpack(z, n1, n2)
    if not np.isfinite(omega2):
        return np.full(p1.shape[0] * p2.shape[0] * _N_STATE + 3, 1e6)

    m1, m2 = p1.shape[0], p2.shape[0]
    u = np.empty((_N_STATE, m1, m2))
    du1 = np.empty((_N_STATE, m1, m2))
    du2 = np.empty((_N_STATE, m1, m2))
    for c in range(_N_STATE):
        cc = coeffs[c]
        u[c] = p1 @ cc @ p2.T
        du1[c] = p1d @ cc @ p2.T
        du2[c] = p1 @ cc @ p2d.T

    rhs = _crnbp_rhs_grid(u, mu, perturbers)
    lhs = omega1 * du1 + omega2 * du2
    pde_res = (lhs - rhs).reshape(-1)

    _, sin1_col_t2 = _k2_first_harmonic_cols(n2)
    phase2 = coeffs[phase2_coord, 0, sin1_col_t2]
    amp = _transverse_amplitude(coeffs, n2)
    gauge = np.array(
        [
            gauge_weight * phase2,
            gauge_weight * (amp - amplitude_anchor),
            rho_weight * (omega2 - rho_target * omega1),
        ]
    )
    return np.concatenate([pde_res, gauge])


def _jacobian(
    z: NDArray[np.float64],
    omega1: float,
    mu: float,
    perturbers: tuple[_PerturberGrid, ...],
    n1: int,
    n2: int,
    p1: NDArray[np.float64],
    p1d: NDArray[np.float64],
    p2: NDArray[np.float64],
    p2d: NDArray[np.float64],
    phase2_coord: int,
    amplitude_anchor: float,
    gauge_weight: float,
    rho_target: float,
    rho_weight: float,
) -> NDArray[np.float64]:
    """Analytic Jacobian of :func:`_residual` (exact; no finite differencing).

    Same block structure as `#690`'s ``_jacobian``.
    """
    coeffs, omega2 = _unpack(z, n1, n2)
    a1n, a2n = 2 * n1 + 1, 2 * n2 + 1
    m1, m2 = p1.shape[0], p2.shape[0]
    n_coef = _N_STATE * a1n * a2n
    n_free = n_coef + 1
    n_pde = _N_STATE * m1 * m2
    jac = np.zeros((n_pde + 3, n_free))

    b_val = np.einsum("ia,jb->ijab", p1, p2)
    b_d1 = np.einsum("ia,jb->ijab", p1d, p2)
    b_d2 = np.einsum("ia,jb->ijab", p1, p2d)
    lhs_basis = (omega1 * b_d1 + omega2 * b_d2).reshape(m1 * m2, a1n * a2n)
    val_basis = b_val.reshape(m1 * m2, a1n * a2n)

    u = np.empty((_N_STATE, m1, m2))
    du2 = np.empty((_N_STATE, m1, m2))
    for c in range(_N_STATE):
        u[c] = p1 @ coeffs[c] @ p2.T
        du2[c] = p1 @ coeffs[c] @ p2d.T
    jf = _crnbp_jacobian_grid(u, mu, perturbers)  # (4,4,m1,m2)

    for c in range(_N_STATE):
        rows = slice(c * m1 * m2, (c + 1) * m1 * m2)
        cols_c = slice(c * a1n * a2n, (c + 1) * a1n * a2n)
        jac[rows, cols_c] = lhs_basis
        for d in range(_N_STATE):
            cols_d = slice(d * a1n * a2n, (d + 1) * a1n * a2n)
            jf_cd = jf[c, d].reshape(m1 * m2)
            jac[rows, cols_d] -= jf_cd[:, None] * val_basis
        jac[rows, n_coef] = du2[c].reshape(m1 * m2)

    cos1_col_t2, sin1_col_t2 = _k2_first_harmonic_cols(n2)

    def _coef_index(c: int, a: int, b: int) -> int:
        return c * a1n * a2n + a * a2n + b

    jac[n_pde + 0, _coef_index(phase2_coord, 0, sin1_col_t2)] = gauge_weight
    amp = _transverse_amplitude(coeffs, n2)
    if amp > 0:
        for c in range(_N_STATE):
            for a in range(a1n):
                jac[n_pde + 1, _coef_index(c, a, cos1_col_t2)] = (
                    gauge_weight * coeffs[c, a, cos1_col_t2] / amp
                )
                jac[n_pde + 1, _coef_index(c, a, sin1_col_t2)] = (
                    gauge_weight * coeffs[c, a, sin1_col_t2] / amp
                )
    jac[n_pde + 2, n_coef] = rho_weight
    return jac


